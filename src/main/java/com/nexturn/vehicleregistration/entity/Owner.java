package com.nexturn.vehicleregistration.entity;

import java.time.Instant;
import java.time.LocalDate;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.nexturn.vehicleregistration.enums.AccountStatus;
import com.nexturn.vehicleregistration.enums.IdentityProofType;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * Represents a vehicle owner's account and personal details.
 *
 * <p>Maps to the existing {@code owner_details} table. Owner accounts do not
 * contain a role field. The authentication response identifies an owner
 * using the value {@code OWNER}.
 */
@Entity
@Table(name = "owner_details")
public class Owner {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long ownerId;

    @Column(nullable = false, length = 30)
    private String firstName;

    @Column(nullable = false, length = 30)
    private String lastName;

    /**
     * Unique email address. The authentication service normalizes it
     * before registration.
     */
    @Column(nullable = false, unique = true, length = 100)
    private String emailAddress;

    @Column(nullable = false, length = 15)
    private String phoneNumber;

    /**
     * Stores the password hash generated by the password utility.
     * Excluded from JSON serialization.
     */
    @JsonIgnore
    @Column(nullable = false, length = 255)
    private String password;

    @Column(nullable = false)
    private LocalDate dateOfBirth;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private IdentityProofType identityProofType;

    @Column(nullable = false, unique = true, length = 30)
    private String identityProofNumber;

    @Column(nullable = false, length = 150)
    private String address;

    @Column(nullable = false, length = 50)
    private String cityName;

    @Column(nullable = false, length = 50)
    private String stateName;

    @Column(nullable = false, length = 6)
    private String pincode;

    /**
     * Newly registered owners are active by default.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private AccountStatus status = AccountStatus.ACTIVE;

    @Column(nullable = false)
    private Instant dateOfCreation = Instant.now();

    /**
     * Initially assigned when the object is created.
     * Update operations must explicitly maintain this value.
     */
    @Column(nullable = false)
    private Instant dateOfUpdate = Instant.now();

    public Long getOwnerId() {
        return ownerId;
    }

    public void setOwnerId(Long ownerId) {
        this.ownerId = ownerId;
    }

    public String getFirstName() {
        return firstName;
    }

    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    public String getEmailAddress() {
        return emailAddress;
    }

    public void setEmailAddress(String emailAddress) {
        this.emailAddress = emailAddress;
    }

    public String getPhoneNumber() {
        return phoneNumber;
    }

    public void setPhoneNumber(String phoneNumber) {
        this.phoneNumber = phoneNumber;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public LocalDate getDateOfBirth() {
        return dateOfBirth;
    }

    public void setDateOfBirth(LocalDate dateOfBirth) {
        this.dateOfBirth = dateOfBirth;
    }

    public IdentityProofType getIdentityProofType() {
        return identityProofType;
    }

    public void setIdentityProofType(IdentityProofType identityProofType) {
        this.identityProofType = identityProofType;
    }

    public String getIdentityProofNumber() {
        return identityProofNumber;
    }

    public void setIdentityProofNumber(String identityProofNumber) {
        this.identityProofNumber = identityProofNumber;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getCityName() {
        return cityName;
    }

    public void setCityName(String cityName) {
        this.cityName = cityName;
    }

    public String getStateName() {
        return stateName;
    }

    public void setStateName(String stateName) {
        this.stateName = stateName;
    }

    public String getPincode() {
        return pincode;
    }

    public void setPincode(String pincode) {
        this.pincode = pincode;
    }

    public AccountStatus getStatus() {
        return status;
    }

    public void setStatus(AccountStatus status) {
        this.status = status;
    }

    public Instant getDateOfCreation() {
        return dateOfCreation;
    }

    public void setDateOfCreation(Instant dateOfCreation) {
        this.dateOfCreation = dateOfCreation;
    }

    public Instant getDateOfUpdate() {
        return dateOfUpdate;
    }

    public void setDateOfUpdate(Instant dateOfUpdate) {
        this.dateOfUpdate = dateOfUpdate;
    }
}
